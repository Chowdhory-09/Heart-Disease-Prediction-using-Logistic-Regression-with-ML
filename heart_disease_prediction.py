# 1. Import Libraries
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

#create a dataframe
df=pd.read_csv("heart.csv")
df.head()

#To get the no. of rows and column
df.shape

#to get the details info about datarame
df.info()

#to get statistical info about datafeame
df.describe()

#Check missing values
df.isnull().sum()

from sklearn.impute import SimpleImputer

num_cols = ['glucose', 'totChol', 'BMI', 'heartRate','cigsPerDay']
cat_cols = ['education', 'BPMeds']

num_imputer = SimpleImputer(strategy='median')
df[num_cols] = num_imputer.fit_transform(df[num_cols])

cat_imputer = SimpleImputer(strategy='most_frequent')
df[cat_cols] = cat_imputer.fit_transform(df[cat_cols])

df.isnull().sum()

import matplotlib.pyplot as plt
import seaborn as sns

# Class balance
print(df['TenYearCHD'].value_counts(normalize=True))
sns.countplot(x='TenYearCHD', data=df)
plt.title('CHD Class Distribution')
plt.show()

# Correlation heatmap
plt.figure(figsize=(12,10))
sns.heatmap(df.corr(), annot=True, fmt='.2f', cmap='coolwarm')
plt.title('Feature Correlation Heatmap')
plt.show()

#create a histogram
df.hist(figsize=(12,12))
plt.savefig('feaguresplot')

#Choose x and y
x=df.iloc[:,:-1]
y=df.iloc[:,-1]

#split dataset into training and tsting
from sklearn.model_selection import train_test_split
x_train, x_test, y_train, y_test=train_test_split(x,y, test_size=0.2, random_state=42, stratify=y)

x_test

y_test

#create a Logistic Regression
from sklearn.linear_model import LogisticRegression
model=LogisticRegression()

#trained the model
model.fit(x_train, y_train)

y_prediction=model.predict(x_test)
print(y_prediction)

#to get the accuracy
from sklearn.metrics import accuracy_score
print('Accuracy of the model is =',
      accuracy_score(y_test, y_prediction))

from sklearn.metrics import classification_report
print(classification_report(y_test, y_prediction))

